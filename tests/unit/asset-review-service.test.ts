import test from 'node:test';
import assert from 'node:assert/strict';
import {createHmac,randomUUID} from 'node:crypto';
import {mkdtemp,mkdir,realpath,rm,readFile,writeFile} from 'node:fs/promises';
import {join,relative,isAbsolute} from 'node:path';
import {tmpdir} from 'node:os';
import {createAssetService} from '../../apps/daemon/src/asset-service.js';
import {AssetReviewStore} from '../../apps/daemon/src/asset-review-store.js';
import {assetReviewCanonical,type AssetReviewReceiptAuthority} from '../../apps/daemon/src/asset-review.js';
import {ConversationWorkStore} from '../../packages/storage/src/conversation-work-store.js';
import {createNativeAssetRegistry} from '../../apps/daemon/src/native-asset-authority.js';
import {saveStudioFixture} from '../../packages/asset-pipeline/testing/studio-import-fixture.js';

const JOB='11111111-1111-4111-8111-111111111111';
const refused=(code:string)=>(error:unknown)=>!!error&&typeof error==='object'&&'code'in error&&error.code===code;
async function fixture(t:test.TestContext,gate=true){
  const boundary=await realpath(tmpdir()),root=await mkdtemp(join(boundary,'arcane-reviewed-import-')),projectPath=await realpath(root),outputRoot=join(root,'outputs');
  const source=join(outputRoot,'test-kit-'+JOB);await mkdir(source,{recursive:true});await saveStudioFixture(source,JOB);
  const work=new ConversationWorkStore({directory:join(root,'work'),projectPath}),conversation={provider:'codex' as const,threadId:'reviewed-native-thread',sessionId:null};
  work.bind({conversation,kind:'asset-job',id:JOB});
  const registry=createNativeAssetRegistry({projectPath}),incarnation=registry.issue(),binding={connectionId:'connection',threadId:conversation.threadId};
  incarnation.seal({...binding,...conversation});incarnation.grant(binding);incarnation.dispatched({...binding,operationId:'first-intent'});
  const actor=registry.capture(incarnation.credential(),'mutate'),scope={projectId:work.projectId,conversation};
  const privateDirectory=join(root,'private');await mkdir(privateDirectory,{mode:0o700});
  const sign=(value:unknown)=>createHmac('sha256','only-owned-synthetic-review-key').update(assetReviewCanonical(value)).digest('hex');
  const authority:AssetReviewReceiptAuthority={directory:privateDirectory,sign,verify:(value,signature)=>signature===sign(value),withSnapshot:evaluate=>evaluate(),close(){}};
  const proof=Symbol('human'),review=new AssetReviewStore({projectPath,authority,authorizeHuman:(_command,value)=>value===proof});
  let selections=0,selectionActive=false;
  const options={cwd:root,projectPath,outputRoot,studioImport:{workAssociations:work,selectTarget(){selections++;selectionActive=true;return {
    target:{sessionId:'offline-target',placeId:0,universeId:0,root:'Workspace' as const,parentRef:'parent',creator:{kind:'user' as const,id:'123'}},
    placement:{mode:'origin' as const},studsPerMeter:1/.28};},validateTarget(){if(!selectionActive)throw Object.assign(Error('Preparation target already released'),{code:'FIXTURE_TARGET_RELEASED'});},releaseTarget(){selectionActive=false;}},...(gate?{modelReview:review}:{})};
  let service=await createAssetService(options);
  t.after(async()=>{await service.close();review.close();registry.close();work.close();const part=relative(boundary,root);assert.ok(part.startsWith('arcane-reviewed-import-')&&!isAbsolute(part)&&!part.includes('..'));await rm(root,{recursive:true,force:true});});
  return {source,scope,actor,incarnation,registry,binding,review,get service(){return service;},get selections(){return selections;},get selectionActive(){return selectionActive;},
    async approve(){const subject=await service.modelReviewSubject(JOB,scope),pending=review.prepare(subject);return review.decide({reviewId:pending.reviewId,decision:'approved',idempotencyKey:randomUUID()},subject,proof);},
    reject(reviewId:string,subject:Parameters<typeof review.decide>[1]){return review.decide({reviewId,decision:'rejected',idempotencyKey:randomUUID()},subject,proof);},
    async restart(){await service.close();service=await createAssetService(options);},
  };
}

test('direct non-UI AssetService payload admission denies pending and missing review before selecting any Studio target',async t=>{
  const f=await fixture(t);
  await assert.rejects(f.service.prepareStudioImportPayload(JOB,f.actor),refused('ASSET_REVIEW_REQUIRED'));assert.equal(f.selections,0);
  const preparation=await f.service.prepareStudioImport(JOB,f.actor);assert.equal(preparation.manifest.revisionId,JOB);assert.equal(f.selections,1,'read-only preparation remains available');
});

test('direct service requires configured human review authority even when all generated bytes and native actor are valid',async t=>{
  const f=await fixture(t,false);assert.equal((await f.service.modelReviewSubject(JOB,f.scope)).jobId,JOB);
  await assert.rejects(f.service.reviewImport(JOB,f.actor),refused('ASSET_REVIEW_REQUIRED'));
  await assert.rejects(f.service.prepareStudioImportPayload(JOB,f.actor),refused('ASSET_REVIEW_REQUIRED'));assert.equal(f.selections,0);
});

test('verified human approval pins the actual full manifest and both GLBs, then payload preparation retains a private live review guard',async t=>{
  const f=await fixture(t),approved=await f.approve(),data=await f.service.prepareStudioImportPayload(JOB,f.actor);
  assert.equal(data.review.reference.reviewId,approved.review.reviewId);assert.equal(data.review.subject.jobId,JOB);
  assert.equal(f.selectionActive,false,'the returned payload guard outlives the completed preparation capture');
  assert.deepEqual(data.review.subject.artifacts.map(a=>a.path),['asset.glb','collision.glb']);assert.equal(data.payload.objects.length,8);
  data.review.assertCurrent();f.service.assertReviewedImport(JOB,f.scope,data.review.reference);
  f.reject(approved.review.reviewId,data.review.subject);
  assert.throws(()=>data.review.assertCurrent(),refused('ASSET_REVIEW_REJECTED'));
  assert.throws(()=>f.service.assertReviewedImport(JOB,f.scope,data.review.reference),refused('ASSET_REVIEW_REJECTED'));
});

test('every returned and cached effect guard fences changed actual export bytes before a later command',async t=>{
  const f=await fixture(t);await f.approve();const guard=await f.service.reviewImport(JOB,f.actor);
  const path=join(f.source,'collision.glb'),bytes=await readFile(path);bytes[bytes.length-1]=bytes[bytes.length-1]!^1;await writeFile(path,bytes);
  assert.throws(()=>guard.assertCurrent(),refused('ASSET_REVIEW_SOURCE'));
  assert.throws(()=>f.service.assertReviewedImport(JOB,f.scope,guard.reference),refused('ASSET_REVIEW_SOURCE'));
  await assert.rejects(f.service.reviewImport(JOB,f.actor));assert.equal(f.selections,0);
});

test('file witnesses cover the full manifest and a changed canonical manifest cannot inherit approval',async t=>{
  const f=await fixture(t);await f.approve();const guard=await f.service.reviewImport(JOB,f.actor),path=join(f.source,'manifest.json');
  const manifest=JSON.parse(await readFile(path,'utf8'));manifest.limitations.push('A new source observation.');await writeFile(path,JSON.stringify(manifest));
  assert.throws(()=>guard.assertCurrent(),refused('ASSET_REVIEW_SOURCE'));
  const changed=await f.service.modelReviewSubject(JOB,f.scope);assert.notEqual(changed.manifestSha256,guard.subject.manifestSha256);
  await assert.rejects(f.service.reviewImport(JOB,f.actor),refused('ASSET_REVIEW_REQUIRED'));
});

test('model cache is not a native actor, cannot change scope, and does not survive a backend restart',async t=>{
  const f=await fixture(t);await f.approve();const guard=await f.service.reviewImport(JOB,f.actor);
  f.incarnation.ended('first-intent');assert.throws(()=>guard.assertCurrent(),refused('NATIVE_ASSET_AUTHORITY'));
  assert.doesNotThrow(()=>f.service.assertReviewedImport(JOB,f.scope,guard.reference),'model witness does not revive an old actor');
  assert.throws(()=>f.service.assertReviewedImport(JOB,{...f.scope,conversation:{...f.scope.conversation,sessionId:'changed'}},guard.reference),refused('ASSET_REVIEW_REQUIRED'),'a different exact conversation has no process-owned review witness');
  await f.restart();assert.throws(()=>f.service.assertReviewedImport(JOB,f.scope,guard.reference),refused('ASSET_REVIEW_REQUIRED'));
});
